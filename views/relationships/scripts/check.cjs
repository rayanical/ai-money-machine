const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path');
require('../core.js');
const C = globalThis.GraphCore;
const dataDir = process.argv[2] || path.join(__dirname, '../../../public/data');
const output = process.argv[3] || path.join(__dirname, '../../../public/relationships/index.html');
const read = name => fs.readFileSync(path.join(dataDir, name), 'utf8');
const entities = JSON.parse(read('entities.json')), relations = JSON.parse(read('relations.json'));
const graph = C.normalize(entities, relations);
assert.equal(graph.nodes.length, entities.entities.length);
assert.equal(graph.edges.length, relations.relations.length);
assert(graph.nodes.every(n => n.layer && n.layer !== 'Other'));
const ledger = C.matchDeals(JSON.parse(read('deal-ledger.json')), graph.nodes);
assert.equal(ledger.deals.length, JSON.parse(read('deal-ledger.json')).deals.length);
const html = fs.readFileSync(output, 'utf8');
const match = html.match(/<script id="bundled-data" type="application\/json">([\s\S]*?)<\/script>/);
assert(match, 'Standalone HTML must contain the snapshot');
const bundle = JSON.parse(match[1]);
assert.deepEqual(bundle.entities, entities);
assert.deepEqual(bundle.relations, relations);
assert.deepEqual(bundle.ledger, JSON.parse(read('deal-ledger.json')));
assert.deepEqual(bundle.meta, JSON.parse(read('shared-snapshot.json')));
assert(bundle.provenance.length > 0);
assert(bundle.provenance.some(row => row.backs_kind === 'relationship' && graph.edges.some(e => e.id === row.backs_id)));
const ns = [{id:'a',name:'A'},{id:'b',name:'B'},{id:'c',name:'C'}];
const m = C.normalize(ns,[{source:'a',target:'b',type:'invests_in'},{source:'b',target:'a',type:'rents'}]);
assert.equal(C.degrees(m.nodes,m.edges).get('a').neighbors.size,1);
assert.equal(C.dualPairs(m.edges).size,1);
assert.equal(C.shortestPath('c','a',m.edges,true),null);
assert.deepEqual(C.shortestPath('a','a',m.edges,true).nodes,['a']);
assert.throws(()=>C.normalize(ns,[{source:'a',target:'missing',type:'rents'}]),/unknown endpoint/);
assert.throws(()=>C.normalize(ns,[{source:'a',target:'b',type:'rents'},{source:'a',target:'b',type:'rents'}]),/Duplicate relationship/);
assert.throws(()=>C.normalize([...ns,{id:'a',name:'Another'}],m.edges),/Duplicate entity/);
assert.throws(()=>C.normalize(ns,[{source:'a',target:'b',type:'rents',as_of:'2026-02-30'}]),/Invalid as_of/);
assert.throws(()=>C.normalize(ns,[{source:'a',target:'b',type:'rents',as_of:'2026-13'}]),/Invalid as_of/);
assert.equal(C.url('javascript:alert(1)'),'');
assert.throws(()=>C.matchDeals({},ns,[{alias:'Unknown',company_id:'missing'}]),/missing company_id/);
console.log(`PASS: ${graph.nodes.length} entities, ${graph.edges.length} links, ${ledger.deals.length} deals; shared bundle, citations, graph behavior and validation.`);
